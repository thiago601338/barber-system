const assert=require('node:assert/strict')
const {test}=require('node:test')
const load=()=>import('../src/lib/subscriptionInvite.ts')
const plan='0f9d2b6e-3c1a-4d55-9a7e-2b1c4d5e6f70'
test('link de convite aponta para a página de assinatura da barbearia e só leva código de plano válido',async()=>{
 const {inviteSuffix,invitePath}=await load()
 assert.equal(inviteSuffix(),'/assinar')
 assert.equal(inviteSuffix(plan.toUpperCase()),`/assinar?plano=${plan}`)
 assert.equal(inviteSuffix('x" onload='),'/assinar')
 assert.equal(invitePath('kingsman',plan),`/b/kingsman/assinar?plano=${plan}`)
 assert.equal(invitePath('kingsman'),'/b/kingsman/assinar')
})
test('plano do convite e retorno após o login aceitam apenas o formato do convite',async()=>{
 const {invitedPlanId,isInviteReturn}=await load()
 assert.equal(invitedPlanId(`?plano=${plan}&utm_source=whatsapp`),plan)
 assert.equal(invitedPlanId('?plano=todos'),null)
 assert.equal(invitedPlanId(''),null)
 assert.equal(isInviteReturn('/b/kingsman/assinar'),true)
 assert.equal(isInviteReturn(`/b/kingsman/assinar?plano=${plan}`),true)
 for(const value of [null,undefined,'','/b/kingsman','/b/kingsman/agendar','//evil.example/b/kingsman/assinar','https://evil.example/b/kingsman/assinar','/b/kingsman/assinar?plano=1','/b/kingsman/assinar/../../master',`/b/kingsman/assinar?plano=${plan}&next=//evil.example`])assert.equal(isInviteReturn(value),false,String(value))
})
test('mensagem do convite cita o plano escolhido e termina com o link',async()=>{
 const {inviteMessage}=await load()
 const one=inviteMessage({shopName:'Kingsman',planName:' Classic Corte ',url:'https://x.test/b/kingsman/assinar'})
 assert.match(one,/o plano Classic Corte da Kingsman/);assert.ok(one.endsWith('https://x.test/b/kingsman/assinar'))
 assert.match(inviteMessage({shopName:'Kingsman',url:'u'}),/um plano da Kingsman/)
})
test('anotação interna da importação não aparece como descrição do plano; intervalo de cobrança fica legível',async()=>{
 const {planBlurb,cycleLabel}=await load()
 assert.equal(planBlurb('Plano migrado do CashBarber (id 20146). Cobrança mensal · plano oculto (venda restrita).'),null)
 assert.equal(planBlurb('  Corte e barba toda semana. '),'Corte e barba toda semana.')
 assert.equal(planBlurb(null),null)
 assert.equal(cycleLabel(1),'por mês');assert.equal(cycleLabel(3),'a cada 3 meses');assert.equal(cycleLabel(undefined),'por mês')
})
